#!/usr/bin/env node
// Feature-level frontend coverage audit.
//
// The two sibling scripts (find-real-missing.mjs, curate-missing-features.mjs)
// answer "which page is missing a button?" — they only look at mutations on a
// page's *primary domain*. By construction they are BLIND to a router that has
// no page at all: no page → no primary-domain signal → invisible.
//
// This script closes that blind spot. It works one level up, at the router
// (feature) granularity, and answers: "for every backend capability, does the
// frontend call it AT ALL, from anywhere?" It classifies each top-level tRPC
// router as ORPHANED (0 procedures reached from the client), PARTIAL, or
// COVERED, and lists the exact unreached procedures.
//
// Input:  /tmp/server-procs.txt  — generated by:
//           pnpm exec tsx scripts/dump-trpc-paths.ts > /tmp/server-procs.txt
//         (path<TAB>type, one procedure per line — the LIVE appRouter)
// Output: docs/FEATURE_COVERAGE.md
//
// Matching is deliberately generous to avoid false orphans: a procedure counts
// as "reached" if its full dotted path (e.g. `cogs.profitability`) appears
// anywhere in client/src as an identifier path — this catches `trpc.X.Y.*`,
// `utils.X.Y.invalidate()`, `trpcClient.X.Y.query()`, `getQueryKey(trpc.X.Y)`,
// etc., regardless of the local variable name. It is a heuristic, not a
// type-checker; see caveats in the emitted doc.

import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = process.cwd();
const CLIENT = join(ROOT, "client/src");
const PROCS_FILE = "/tmp/server-procs.txt";

// Routers that are intentionally headless — no UI is expected. Kept small and
// explicit so the report doesn't cry wolf over deliberate stubs / pure helpers
// / internal plumbing. Everything NOT listed here that comes back orphaned is a
// genuine "backend with no frontend" candidate.
const EXPECTED_HEADLESS = {
  system: "health/version plumbing",
  agent: "internal agent runtime hooks",
  bills: "deliberate stub — throws NOT_IMPLEMENTED, redirects to POs/QuickBooks",
  productionOrders: "deliberate stub — superseded by workOrders",
  moisture: "stateless calculators — helper for other features, not a screen",
};

function listSource(dir) {
  const out = [];
  for (const e of readdirSync(dir)) {
    const p = join(dir, e);
    if (statSync(p).isDirectory()) out.push(...listSource(p));
    else if (/\.(tsx?|jsx?)$/.test(e)) out.push(p);
  }
  return out;
}

// --- Load server procedures -------------------------------------------------
let procsRaw;
try {
  procsRaw = readFileSync(PROCS_FILE, "utf8");
} catch {
  console.error(
    `[feature-coverage] Missing ${PROCS_FILE}.\n` +
      `Generate it first:\n` +
      `  pnpm exec tsx scripts/dump-trpc-paths.ts > ${PROCS_FILE}`,
  );
  process.exit(1);
}

/** top-level router key -> { procs: [{path, type}] } */
const routers = new Map();
for (const line of procsRaw.split("\n")) {
  if (!line.trim()) continue;
  const [path, type = "unknown"] = line.split("\t");
  if (!path || !path.includes(".")) continue; // skip malformed / bare keys
  const top = path.split(".")[0];
  if (!routers.has(top)) routers.set(top, { procs: [] });
  routers.get(top).procs.push({ path, type: type.trim() });
}

if (routers.size === 0) {
  console.error(`[feature-coverage] ${PROCS_FILE} parsed to 0 routers — is it empty or stale?`);
  process.exit(1);
}

// --- Concatenate client source ---------------------------------------------
const clientText = listSource(CLIENT)
  .map((f) => readFileSync(f, "utf8"))
  .join("\n");

// Router aliases: `const codeApi = trpc.code` then `codeApi.snippets.useQuery()`.
// Without this the alias hides the router's procedures from the literal-path
// scan below. Map aliasName -> routerKey for every top-level-router alias.
const aliasToRouter = new Map();
for (const m of clientText.matchAll(/(?:const|let|var)\s+(\w+)\s*=\s*trpc\.(\w+)(?![\w.])/g)) {
  if (routers.has(m[2])) aliasToRouter.set(m[1], m[2]);
}
const aliasesByRouter = new Map();
for (const [alias, router] of aliasToRouter) {
  if (!aliasesByRouter.has(router)) aliasesByRouter.set(router, []);
  aliasesByRouter.get(router).push(alias);
}

// A proc path is "reached" if it appears as an identifier path anywhere in the
// client. Boundaries: not preceded/followed by a word char (a leading `.` from
// `trpc.`/`utils.` is allowed since `.` is not a word char). Also resolves
// router aliases so `codeApi.snippets` counts for `code.snippets`.
const reachCache = new Map();
function isReached(path) {
  if (reachCache.has(path)) return reachCache.get(path);
  const esc = path.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  let hit = new RegExp(`(?<![\\w])${esc}(?![\\w])`).test(clientText);
  if (!hit) {
    const dot = path.indexOf(".");
    const router = path.slice(0, dot);
    const rest = path.slice(dot + 1);
    for (const alias of aliasesByRouter.get(router) || []) {
      const aliasEsc = `${alias}.${rest}`.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
      if (new RegExp(`(?<![\\w])${aliasEsc}(?![\\w])`).test(clientText)) {
        hit = true;
        break;
      }
    }
  }
  reachCache.set(path, hit);
  return hit;
}

// --- Classify ---------------------------------------------------------------
const rows = [];
for (const [key, { procs }] of routers) {
  const reached = procs.filter((p) => isReached(p.path));
  const unreached = procs.filter((p) => !isReached(p.path));
  const total = procs.length;
  const pct = total ? Math.round((reached.length / total) * 100) : 0;
  let status;
  if (reached.length === 0) status = EXPECTED_HEADLESS[key] ? "HEADLESS" : "ORPHANED";
  else if (pct < 50) status = "PARTIAL";
  else status = "COVERED";
  rows.push({
    key,
    total,
    reached: reached.length,
    pct,
    status,
    unreached,
    note: EXPECTED_HEADLESS[key] || "",
  });
}

const orphaned = rows.filter((r) => r.status === "ORPHANED").sort((a, b) => b.total - a.total);
const headless = rows.filter((r) => r.status === "HEADLESS").sort((a, b) => a.key.localeCompare(b.key));
const partial = rows
  .filter((r) => r.status === "PARTIAL")
  .sort((a, b) => b.unreached.length - a.unreached.length);
const covered = rows.filter((r) => r.status === "COVERED");

const totalProcs = rows.reduce((s, r) => s + r.total, 0);
const totalReached = rows.reduce((s, r) => s + r.reached, 0);

// --- Emit -------------------------------------------------------------------
const out = [];
out.push("# Feature coverage — backend routers vs. frontend");
out.push("");
out.push("**Generated by `scripts/feature-coverage.mjs`. Do not edit by hand.**");
out.push("");
out.push(
  "Router-level companion to the button-level docs (`UI_MISSING_FEATURES.md`, " +
    "`find-real-missing`). Those find missing *buttons on existing pages*; they " +
    "cannot see a router that has **no page at all** (no page → no primary-domain " +
    "signal). This report works at feature granularity and answers: *does the " +
    "frontend call this backend capability from anywhere?*",
);
out.push("");
out.push("## How to regenerate");
out.push("");
out.push("```sh");
out.push("pnpm exec tsx scripts/dump-trpc-paths.ts > /tmp/server-procs.txt");
out.push("node scripts/feature-coverage.mjs");
out.push("```");
out.push("");
out.push("## Summary");
out.push("");
out.push(`- Top-level routers: **${rows.length}**`);
out.push(`- Procedures (live \`appRouter\`): **${totalProcs}**, reached from client: **${totalReached}** (${Math.round((totalReached / totalProcs) * 100)}%)`);
out.push(`- 🔴 **ORPHANED** (0 procedures reached — real backend with no frontend): **${orphaned.length}**`);
out.push(`- 🟡 **PARTIAL** (<50% of procedures reached): **${partial.length}**`);
out.push(`- 🟢 **COVERED** (≥50% reached): **${covered.length}**`);
out.push(`- ⚪ **HEADLESS** (0 reached, but expected — stubs/helpers/plumbing): **${headless.length}**`);
out.push("");
out.push("## Caveats");
out.push("");
out.push("- Matching is by literal proc-path presence in `client/src`, not type analysis. A path used only inside a comment or dead code would count as reached (rare, and conservative — it under-reports gaps, never over-reports).");
out.push("- ORPHANED = *nothing* in the client references any of the router's procedures. That's the strong signal to act on.");
out.push("- PARTIAL routers already have a page; their unreached procedures overlap with the button-level docs. Use those docs for per-page button work.");
out.push("- HEADLESS routers are annotated exclusions in the script — edit `EXPECTED_HEADLESS` there if one is miscategorized.");
out.push("");

out.push("## 🔴 Orphaned routers — backend features with no UI (priority)");
out.push("");
if (orphaned.length === 0) {
  out.push("_None._");
} else {
  out.push("| Router | Procedures | queries | mutations |");
  out.push("|---|---|---|---|");
  for (const r of orphaned) {
    const q = r.unreached.filter((p) => p.type === "query").length;
    const m = r.unreached.filter((p) => p.type === "mutation").length;
    out.push(`| \`${r.key}\` | ${r.total} | ${q} | ${m} |`);
  }
  out.push("");
  out.push("### Unreached procedures per orphaned router");
  out.push("");
  for (const r of orphaned) {
    out.push(`#### \`${r.key}\` — ${r.total} procedures, 0 reached`);
    for (const p of r.unreached) out.push(`- \`${p.path}\` _(${p.type})_`);
    out.push("");
  }
}

out.push("## 🟡 Partial routers — page exists, capabilities under-wired");
out.push("");
if (partial.length === 0) {
  out.push("_None._");
} else {
  out.push("| Router | reached / total | % | unreached |");
  out.push("|---|---|---|---|");
  for (const r of partial) {
    out.push(`| \`${r.key}\` | ${r.reached} / ${r.total} | ${r.pct}% | ${r.unreached.length} |`);
  }
  out.push("");
  out.push("<details><summary>Unreached procedures per partial router</summary>");
  out.push("");
  for (const r of partial) {
    out.push(`**\`${r.key}\`** (${r.unreached.length} unreached):`);
    for (const p of r.unreached) out.push(`- \`${p.path}\` _(${p.type})_`);
    out.push("");
  }
  out.push("</details>");
}
out.push("");

out.push("## ⚪ Headless (expected — no UI intended)");
out.push("");
for (const r of headless) out.push(`- \`${r.key}\` — ${r.note}`);
out.push("");

out.push("## 🟢 Covered routers");
out.push("");
out.push(
  covered
    .sort((a, b) => a.key.localeCompare(b.key))
    .map((r) => `\`${r.key}\` (${r.pct}%)`)
    .join(" · "),
);
out.push("");

writeFileSync(join(ROOT, "docs/FEATURE_COVERAGE.md"), out.join("\n"));
console.error(
  `[feature-coverage] Wrote docs/FEATURE_COVERAGE.md — ` +
    `${rows.length} routers, ${orphaned.length} orphaned, ${partial.length} partial, ` +
    `${covered.length} covered, ${headless.length} headless.`,
);
