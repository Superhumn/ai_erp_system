#!/usr/bin/env node
// Regenerate DB_INDEX.md from the legacy `server/db.ts` monolith.
// Keeps the main conversation context lean: jump to line ranges instead of
// reading 17k lines.
//
// (ROUTERS_INDEX.md is gone: `server/routers.ts` was split into one file per
// top-level key under `server/routers/`, so the directory listing is the index.)

import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

function readLines(rel) {
  return readFileSync(join(ROOT, rel), 'utf8').split('\n');
}

// ─── db.ts ───────────────────────────────────────────────────────────────────

function parseDb() {
  const lines = readLines('server/db.ts');
  const bannerRe = /^\s*\/\/\s*=+\s*$/;
  const titleRe = /^\s*\/\/\s*([A-Z][^=\n]*?)\s*$/;
  const exportRe = /^export\s+(?:async\s+)?(?:function|const|let|var|type|interface)\s+(\w+)/;

  // Detect banners: three consecutive comment-style lines:
  //   // ============
  //   // TITLE
  //   // ============
  const sections = [];
  for (let i = 0; i < lines.length - 2; i++) {
    if (bannerRe.test(lines[i]) && titleRe.test(lines[i + 1]) && bannerRe.test(lines[i + 2])) {
      const title = titleRe.exec(lines[i + 1])[1].trim();
      sections.push({ title, line: i + 1, exports: [] });
      i += 2;
    }
  }

  // Collect all exports with line numbers.
  const exports = [];
  for (let i = 0; i < lines.length; i++) {
    const m = exportRe.exec(lines[i]);
    if (m) exports.push({ name: m[1], line: i + 1 });
  }

  // Assign each export to the latest section whose line <= export.line.
  // If no section yet, put in "(preamble)".
  const preamble = { title: '(preamble — connection, types, helpers)', line: 1, exports: [] };
  const allSections = [preamble, ...sections];
  for (const e of exports) {
    let target = preamble;
    for (const s of sections) {
      if (s.line <= e.line) target = s;
      else break;
    }
    target.exports.push(e);
  }

  // Set endLine per section.
  for (let i = 0; i < allSections.length; i++) {
    allSections[i].endLine = i + 1 < allSections.length ? allSections[i + 1].line - 1 : lines.length;
  }

  return { totalLines: lines.length, totalExports: exports.length, sections: allSections };
}

function extractedDbExports() {
  const dbDir = join(ROOT, 'server/db');
  const files = readdirSync(dbDir).filter((f) => f.endsWith('.ts') && f !== 'index.ts').sort();
  const byName = new Map(); // export name -> file stem
  const exportRe = /^export\s+(?:async\s+)?(?:function|const|let|var|type|interface)\s+(\w+)/gm;
  for (const f of files) {
    const stem = f.replace(/\.ts$/, '');
    const src = readFileSync(join(dbDir, f), 'utf8');
    let m;
    exportRe.lastIndex = 0;
    while ((m = exportRe.exec(src)) !== null) {
      if (!byName.has(m[1])) byName.set(m[1], stem);
    }
  }
  return byName;
}

function renderDbIndex() {
  const { totalLines, totalExports, sections } = parseDb();
  const extracted = extractedDbExports();

  const lines = [];
  lines.push('# server/db.ts — line-range index');
  lines.push('');
  lines.push('**Generated by `pnpm index:legacy`. Do not edit by hand.**');
  lines.push('');
  lines.push(`Source: \`server/db.ts\` (${totalLines} lines, ${totalExports} top-level exports, ${sections.length - 1} comment-banner sections).`);
  lines.push('');
  lines.push('> **Rule:** do not `Read` `server/db.ts` in full. Jump to the range for the feature you need, or delegate exploration to an Explore subagent. For any new helper, add it to `server/db/<feature>.ts` (see table below for the convention).');
  lines.push('');
  lines.push('## Section map (by `// === BANNER ===` comment)');
  lines.push('');
  lines.push('| # | Section | Lines | Exports | Extracted coverage |');
  lines.push('|---|---|---|---|---|');
  sections.forEach((s, i) => {
    const covered = s.exports.filter((e) => extracted.has(e.name)).length;
    const pct = s.exports.length ? Math.round((covered / s.exports.length) * 100) : 0;
    lines.push(`| ${i} | ${s.title} | L${s.line}–L${s.endLine} | ${s.exports.length} | ${covered}/${s.exports.length} (${pct}%) |`);
  });
  lines.push('');
  lines.push('## Per-section export listings');
  lines.push('');
  for (const s of sections) {
    if (s.exports.length === 0) continue;
    lines.push(`### ${s.title}  L${s.line}–L${s.endLine}`);
    lines.push('');
    for (const e of s.exports) {
      const ex = extracted.get(e.name);
      const tag = ex ? `✓ \`db/${ex}\`` : '✗ legacy-only';
      lines.push(`- \`${e.name}\` — L${e.line} — ${tag}`);
    }
    lines.push('');
  }
  return lines.join('\n');
}

// ─── main ───────────────────────────────────────────────────────────────────

const dbMd = renderDbIndex();
writeFileSync(join(ROOT, 'DB_INDEX.md'), dbMd);
console.log(`wrote DB_INDEX.md (${dbMd.split('\n').length} lines)`);
