#!/usr/bin/env node
// Regenerate ROUTERS_INDEX.md and DB_INDEX.md from the two legacy monoliths.
// Keeps the main conversation context lean: jump to line ranges instead of
// reading 21k / 12k lines.

import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

function readLines(rel) {
  return readFileSync(join(ROOT, rel), 'utf8').split('\n');
}

// ─── routers.ts ──────────────────────────────────────────────────────────────

function parseRouters() {
  const lines = readLines('server/routers.ts');
  const openIdx = lines.findIndex((l) => l.startsWith('export const appRouter = router('));
  if (openIdx < 0) throw new Error('appRouter not found');
  // Closing `});` at column 0 after openIdx.
  let closeIdx = -1;
  for (let i = openIdx + 1; i < lines.length; i++) {
    if (/^\}\);?$/.test(lines[i])) { closeIdx = i; break; }
  }
  if (closeIdx < 0) throw new Error('appRouter close not found');

  // Top-level keys: exactly 2-space indent, either `key: router(` or `key: xxxRouter,`.
  const keyRe = /^  ([a-zA-Z][a-zA-Z0-9_]*)\s*:\s*(router\(|[a-zA-Z][a-zA-Z0-9_]*Router,?\s*$)/;
  const keys = [];
  for (let i = openIdx + 1; i < closeIdx; i++) {
    const m = keyRe.exec(lines[i]);
    if (m) keys.push({ name: m[1], line: i + 1 });
  }

  // End-line for each: start of next - 1, or closeIdx for the last.
  for (let j = 0; j < keys.length; j++) {
    const endLine = j + 1 < keys.length ? keys[j + 1].line - 1 : closeIdx;
    keys[j].endLine = endLine;
    keys[j].lineCount = endLine - keys[j].line + 1;
  }
  return { openLine: openIdx + 1, closeLine: closeIdx + 1, keys };
}

function extractedRouterKeys() {
  // Mirror server/routers/index.ts shape: baseRouter keys + keys from each merged router.
  // `code` is mounted as a baseRouter key (a flat router), like `employeePortal`.
  const baseKeys = ['system', 'autonomousWorkflows', 'agent', 'employeePortal', 'taskBridge', 'code'];
  const sources = [
    'auth', 'finance', 'sales', 'crm', 'operations', 'procurement',
    'manufacturing', 'freight', 'edi', 'email', 'hr', 'legal', 'projects',
    'dataRoom', 'settings', 'ai', 'board', 'investorUpdates', 'code',
  ];
  const byKey = new Map(); // key -> file stem
  for (const k of baseKeys) byKey.set(k, 'index (baseRouter)');

  for (const stem of sources) {
    const rel = `server/routers/${stem}.ts`;
    const src = readFileSync(join(ROOT, rel), 'utf8');
    const m = /export const (\w+Router)\s*=\s*router\(\{/.exec(src);
    if (!m) continue;
    // Walk keys at 2-space indent until matching close.
    const body = src.slice(m.index + m[0].length);
    const bodyLines = body.split('\n');
    let depth = 1;
    for (const line of bodyLines) {
      if (depth === 1) {
        const km = /^  ([a-zA-Z][a-zA-Z0-9_]*)\s*:/.exec(line);
        if (km) byKey.set(km[1], stem);
      }
      // brace depth (approximate — strip strings/comments). Template literals
      // are intentionally NOT stripped: their `${…}` interpolations contain
      // balanced `{` / `}` pairs that the naive counter handles correctly,
      // and regex-stripping nested template literals (e.g. `${x ? `a` : `b`}`)
      // breaks more than it fixes.
      const c = line
        .replace(/\/\/.*$/, '')
        .replace(/`(?:\\.|[^`\\])*`/g, '``')
        .replace(/"(?:\\.|[^"\\])*"/g, '""')
        .replace(/'(?:\\.|[^'\\])*'/g, "''");
      depth += (c.match(/\{/g)?.length || 0) - (c.match(/\}/g)?.length || 0);
      if (depth === 0) break;
    }
  }
  return byKey;
}

function renderRoutersIndex() {
  const { openLine, closeLine, keys } = parseRouters();
  const extracted = extractedRouterKeys();

  const only_legacy = keys.filter((k) => !extracted.has(k.name));
  const in_both = keys.filter((k) => extracted.has(k.name));

  const lines = [];
  lines.push('# server/routers.ts — line-range index');
  lines.push('');
  lines.push('**Generated by `pnpm index:legacy`. Do not edit by hand.**');
  lines.push('');
  lines.push(`Source: \`server/routers.ts\` (appRouter L${openLine}–L${closeLine}, ${keys.length} top-level keys).`);
  lines.push('');
  lines.push('> **Rule:** do not `Read` `server/routers.ts` in full. Jump to the range for the feature you need, or delegate exploration to an Explore subagent.');
  lines.push('');
  lines.push('## Top-level routers (sorted by line number)');
  lines.push('');
  lines.push('| Key | Lines | Count | In extracted tree? |');
  lines.push('|---|---|---|---|');
  for (const k of keys) {
    const ex = extracted.get(k.name);
    const status = ex ? `✓ \`server/routers/${ex === 'index (baseRouter)' ? 'index.ts' : ex + '.ts'}\`` : '✗ legacy-only';
    lines.push(`| \`${k.name}\` | L${k.line}–L${k.endLine} | ${k.lineCount} | ${status} |`);
  }
  lines.push('');
  lines.push(`## Legacy-only (${only_legacy.length})`);
  lines.push('');
  lines.push('These exist only in `server/routers.ts` — the extracted `server/routers/` tree does not cover them.');
  lines.push('');
  for (const k of only_legacy) {
    lines.push(`- \`${k.name}\` — L${k.line}–L${k.endLine} (${k.lineCount} lines)`);
  }
  lines.push('');
  lines.push(`## Also in extracted tree (${in_both.length})`);
  lines.push('');
  lines.push('Top-level key exists in both. **Route-level parity is not guaranteed** — spot checks have found legacy-only procedures inside several of these (e.g. `crm` has ~7 legacy-only procedures, `invoices` has 2). If you need completeness, diff the specific sub-router.');
  lines.push('');
  for (const k of in_both) {
    const ex = extracted.get(k.name);
    lines.push(`- \`${k.name}\` — legacy L${k.line}–L${k.endLine} · extracted in \`server/routers/${ex === 'index (baseRouter)' ? 'index.ts' : ex + '.ts'}\``);
  }
  lines.push('');
  return lines.join('\n');
}

// ─── db.ts ───────────────────────────────────────────────────────────────────

function parseDb() {
  const lines = readLines('server/db.ts');
  const bannerRe = /^\s*\/\/\s*=+\s*$/;
  const titleRe = /^\s*\/\/\s*([A-Z][^=\n]*?)\s*$/;
  const exportRe = /^export\s+(?:async\s+)?(?:function|const|let|var|type|interface)\s+(\w+)/;

  // Detect banners: three consecutive comment-style lines:
  //   // ============
  //   // TITLE
  //   // ============
  const sections = [];
  for (let i = 0; i < lines.length - 2; i++) {
    if (bannerRe.test(lines[i]) && titleRe.test(lines[i + 1]) && bannerRe.test(lines[i + 2])) {
      const title = titleRe.exec(lines[i + 1])[1].trim();
      sections.push({ title, line: i + 1, exports: [] });
      i += 2;
    }
  }

  // Collect all exports with line numbers.
  const exports = [];
  for (let i = 0; i < lines.length; i++) {
    const m = exportRe.exec(lines[i]);
    if (m) exports.push({ name: m[1], line: i + 1 });
  }

  // Assign each export to the latest section whose line <= export.line.
  // If no section yet, put in "(preamble)".
  const preamble = { title: '(preamble — connection, types, helpers)', line: 1, exports: [] };
  const allSections = [preamble, ...sections];
  for (const e of exports) {
    let target = preamble;
    for (const s of sections) {
      if (s.line <= e.line) target = s;
      else break;
    }
    target.exports.push(e);
  }

  // Set endLine per section.
  for (let i = 0; i < allSections.length; i++) {
    allSections[i].endLine = i + 1 < allSections.length ? allSections[i + 1].line - 1 : lines.length;
  }

  return { totalLines: lines.length, totalExports: exports.length, sections: allSections };
}

function extractedDbExports() {
  const dbDir = join(ROOT, 'server/db');
  const files = readdirSync(dbDir).filter((f) => f.endsWith('.ts') && f !== 'index.ts').sort();
  const byName = new Map(); // export name -> file stem
  const exportRe = /^export\s+(?:async\s+)?(?:function|const|let|var|type|interface)\s+(\w+)/gm;
  for (const f of files) {
    const stem = f.replace(/\.ts$/, '');
    const src = readFileSync(join(dbDir, f), 'utf8');
    let m;
    exportRe.lastIndex = 0;
    while ((m = exportRe.exec(src)) !== null) {
      if (!byName.has(m[1])) byName.set(m[1], stem);
    }
  }
  return byName;
}

function renderDbIndex() {
  const { totalLines, totalExports, sections } = parseDb();
  const extracted = extractedDbExports();

  const lines = [];
  lines.push('# server/db.ts — line-range index');
  lines.push('');
  lines.push('**Generated by `pnpm index:legacy`. Do not edit by hand.**');
  lines.push('');
  lines.push(`Source: \`server/db.ts\` (${totalLines} lines, ${totalExports} top-level exports, ${sections.length - 1} comment-banner sections).`);
  lines.push('');
  lines.push('> **Rule:** do not `Read` `server/db.ts` in full. Jump to the range for the feature you need, or delegate exploration to an Explore subagent. For any new helper, add it to `server/db/<feature>.ts` (see table below for the convention).');
  lines.push('');
  lines.push('## Section map (by `// === BANNER ===` comment)');
  lines.push('');
  lines.push('| # | Section | Lines | Exports | Extracted coverage |');
  lines.push('|---|---|---|---|---|');
  sections.forEach((s, i) => {
    const covered = s.exports.filter((e) => extracted.has(e.name)).length;
    const pct = s.exports.length ? Math.round((covered / s.exports.length) * 100) : 0;
    lines.push(`| ${i} | ${s.title} | L${s.line}–L${s.endLine} | ${s.exports.length} | ${covered}/${s.exports.length} (${pct}%) |`);
  });
  lines.push('');
  lines.push('## Per-section export listings');
  lines.push('');
  for (const s of sections) {
    if (s.exports.length === 0) continue;
    lines.push(`### ${s.title}  L${s.line}–L${s.endLine}`);
    lines.push('');
    for (const e of s.exports) {
      const ex = extracted.get(e.name);
      const tag = ex ? `✓ \`db/${ex}\`` : '✗ legacy-only';
      lines.push(`- \`${e.name}\` — L${e.line} — ${tag}`);
    }
    lines.push('');
  }
  return lines.join('\n');
}

// ─── main ───────────────────────────────────────────────────────────────────

const routersMd = renderRoutersIndex();
const dbMd = renderDbIndex();

writeFileSync(join(ROOT, 'ROUTERS_INDEX.md'), routersMd);
writeFileSync(join(ROOT, 'DB_INDEX.md'), dbMd);

console.log(`wrote ROUTERS_INDEX.md (${routersMd.split('\n').length} lines)`);
console.log(`wrote DB_INDEX.md (${dbMd.split('\n').length} lines)`);
